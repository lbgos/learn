import { build } from "esbuild";
import * as NodeFSP from "node:fs/promises";

// Committed source text works in Node, Vite and the server bundle without a raw-loader.
const result = await build({
  entryPoints: [new URL("../src/sim/runtime.ts", import.meta.url).pathname],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "inline",
});
await NodeFSP.writeFile(
  new URL("../src/sim/runtimeBundle.ts", import.meta.url),
  `// Generated by scripts/build-runtime.mjs. Three.js MIT license is included in the bundle.\n// Preserve the generated bundle text.\n// prettier-ignore\nexport const simRuntimeBundle = ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
